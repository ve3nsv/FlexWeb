#!/bin/sh
# Regenerates resources/rnnoise/weights.bin and resources/rnnoise/src/rnnoise_init.c
# from an RNNoise source tree (upstream xiph/rnnoise, or AetherSDR's
# third_party/rnnoise) - run it when updating RNNoise, then commit both.
#
# Upstream compiles its trained model in as src/rnnoise_data.c (78 MB of C).
# FlexWeb instead ships the same arrays as RNNoise's own binary weights blob
# (the format parse_lpcnet_weights.c reads: a 64-byte "DNNw" header per array,
# its data padded to 64 bytes) and keeps only init_rnnoise(), the part of
# rnnoise_data.c that wires the arrays into the network; the denoiser loads
# the blob with rnnoise_model_from_buffer() (USE_WEIGHTS_FILE).
#
#   tools/make-rnnoise-weights.sh /path/to/rnnoise
set -eu
SRC=${1:?usage: $0 <rnnoise source dir>}
HERE=$(cd "$(dirname "$0")/.." && pwd)
OUT="$HERE/resources/rnnoise"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
DATA="$SRC/src/rnnoise_data.c"
test -f "$DATA" || { echo "no $DATA" >&2; exit 1; }

cat > "$TMP/dump.c" <<'C'
#include <stdio.h>
#include <string.h>
#include "nnet.h"
extern const WeightArray rnnoise_arrays[];
int main(int argc, char **argv) {
    FILE *f = fopen(argv[1], "wb");
    if (!f) return 1;
    static const unsigned char zeros[WEIGHT_BLOCK_SIZE];
    for (const WeightArray *a = rnnoise_arrays; a->name; ++a) {
        WeightHead h;
        memset(&h, 0, sizeof h);
        memcpy(h.head, "DNNw", 4);
        h.version = WEIGHT_BLOB_VERSION;
        h.type = a->type;
        h.size = a->size;
        h.block_size = (a->size + WEIGHT_BLOCK_SIZE - 1) / WEIGHT_BLOCK_SIZE * WEIGHT_BLOCK_SIZE;
        if (strlen(a->name) >= sizeof h.name) return 2;
        strcpy(h.name, a->name);
        fwrite(&h, sizeof h, 1, f);
        fwrite(a->data, 1, (size_t)a->size, f);
        fwrite(zeros, 1, (size_t)(h.block_size - a->size), f);
    }
    return fclose(f) ? 3 : 0;
}
C
# DUMP_BINARY_WEIGHTS: the arrays without init_rnnoise (which needs the rest of RNNoise)
cc -O0 -DDUMP_BINARY_WEIGHTS -I"$SRC/src" -I"$SRC/include" "$TMP/dump.c" "$DATA" -o "$TMP/dump"
"$TMP/dump" "$OUT/weights.bin"

# init_rnnoise(): everything from the DUMP_BINARY_WEIGHTS guard to the end.
{
    echo "/* Generated by tools/make-rnnoise-weights.sh from rnnoise_data.c"
    echo "   (RNNoise $(cat "$SRC/COMMIT" 2>/dev/null || echo 'unknown commit')): init_rnnoise() only -"
    echo "   the weights themselves are in ../weights.bin. BSD-3-Clause, see ../COPYING. */"
    echo '#ifdef HAVE_CONFIG_H'
    echo '#include "config.h"'
    echo '#endif'
    echo '#include "rnnoise_data.h"'
    echo
    sed -n '/^#ifndef DUMP_BINARY_WEIGHTS/,$p' "$DATA"
} > "$OUT/src/rnnoise_init.c"
ls -l "$OUT/weights.bin" "$OUT/src/rnnoise_init.c"
